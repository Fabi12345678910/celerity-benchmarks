#!/usr/bin/env python3
"""Generates the YAMLs of the task-overhead study (one tiny kernel submitted N times, programs in this folder) for gpuc4, ifi and LUMI:
  overhead_plain              hip, opencl, plain SYCL on AdaptiveCpp and on DPC++ (the baselines)
  overhead_celerity           Celerity (bench branch 2dda28f) with a kernel per task only (strided=0): copylib never runs, so staging base and CELERITY_COPYLIB=off show the executor start-up difference only
  overhead_celerity_strided   kernel + host task reading column 0 per task (strided=1), copylib staging and host kernel (sweep 4 bases), all sizes
  overhead_celerity_native    the same with CELERITY_COPYLIB=off (the native strided path takes ms per copy, so only elems 1 and 1024 and up to 1000 tasks)
All with HSA_ENABLE_SDMA=0 (the standing default). Writes <system>/<name>.yaml, <system>/jobs.txt (ifi, LUMI: one Slurm job per line) and gpuc4/chain.sh. Usage: python3 make_yamls.py
--smoke writes gpuc4/smoke/<name>.yaml instead: tasks 100 and 1000, elems 1 and 1048576 (native: 100 tasks), one iteration, no warmup,
to check every program and configuration once through the wrapper and to measure the runtimes."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SDMA = "HSA_ENABLE_SDMA=0"
STG = f"{SDMA} CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_CHUNK_BYTES=1048576"
HK = f"{STG} COPYLIB_HOST_KERNEL=1 COPYLIB_MAX_ELEM_SIZE=4 COPYLIB_ELEMS_PER_ITEM=4 COPYLIB_WG_SIZE=256"
OFF = f"{SDMA} CELERITY_COPYLIB=off"
DPCPP = ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && "
BIN = "~/finalizing-work/build/overhead"
METRICS = {"machine": r"^(\\S+)", "submit_us_per_task": r"Submit: ([0-9.]+) us/task", "total_us_per_task": r"Total: ([0-9.]+) us/task",
           "drain_us": r"Drain: ([0-9.]+) us", "latency_us": r"Latency: ([0-9.]+) us", "check": r"Check: (\\w+)"}
TASKS, ELEMS, BUFFERS = "100, 1000, 10000", "1, 1024, 1048576", "1, 64"
# (name, [(application, source, binary, uses strided argument)], env list, tasks, elems, buffers, strided list, variant)
STUDIES = [
    ("overhead_plain", [("hip", "", "overhead_hip", False), ("opencl", "", "overhead_opencl", False), ("SYCL-acpp", "", "overhead_acpp", False),
                        ("SYCL-dpcpp", DPCPP, "overhead_dpcpp", False)], [SDMA], TASKS, ELEMS, BUFFERS, None, "plain"),
    ("overhead_celerity", [("Celerity-acpp", "", "overhead_celerity_acpp", True), ("Celerity-dpcpp", DPCPP, "overhead_celerity_dpcpp0326", True)],
     [STG, OFF], TASKS, ELEMS, BUFFERS, [0], "kernel only"),
    ("overhead_celerity_strided", [("Celerity-acpp", "", "overhead_celerity_acpp", True), ("Celerity-dpcpp", DPCPP, "overhead_celerity_dpcpp0326", True)],
     [STG, HK], TASKS, ELEMS, BUFFERS, [1], "strided copy per task"),
    ("overhead_celerity_native", [("Celerity-acpp", "", "overhead_celerity_acpp", True), ("Celerity-dpcpp", DPCPP, "overhead_celerity_dpcpp0326", True)],
     [OFF], "100, 1000", "1, 1024", BUFFERS, [1], "strided copy per task, native"),
]


SMOKE = {"overhead_celerity_native": ("100", "1, 1024")}
# Slurm jobs (one line of jobs.txt each; the first one also builds). ifi jobs may run 2 h at most, so the strided study is split per compiler there.
JOBS = {"ifi": [["overhead_plain", "overhead_celerity"], ["overhead_celerity_strided_acpp"], ["overhead_celerity_strided_dpcpp"], ["overhead_celerity_native"]],
        "lumi": [["overhead_plain", "overhead_celerity"], ["overhead_celerity_strided"], ["overhead_celerity_native"]]}


def main():
    smoke = "--smoke" in sys.argv[1:]
    for system in ("gpuc4",) if smoke else ("gpuc4", "ifi", "lumi"):
        sub = os.path.join(system, "smoke") if smoke else system
        res = os.path.join(system, "results", "smoke") if smoke else os.path.join(system, "results")
        os.makedirs(os.path.join(HERE, sub), exist_ok=True)
        os.makedirs(os.path.join(HERE, res), exist_ok=True)
        prefix = "ROCR_VISIBLE_DEVICES=4 " if system == "lumi" else ""
        names = []
        studies = []
        for st in STUDIES:
            if not smoke and any(st[0] + "_acpp" in job for job in JOBS.get(system, [])):
                studies += [(f"{st[0]}_{app[0].split('-')[1]}", [app]) + st[2:] for app in st[1]]
            else:
                studies.append(st)
        for name, apps, envs, tasks, elems, buffers, stridedvals, variant in studies:
            if smoke:
                tasks, elems = SMOKE.get(name, ("100, 1000", "1, 1048576"))
            reps = ["iterations: 1", "warmup_iterations: 0"] if smoke else ["iterations: 3", "warmup_iterations: 1"]
            out = ["# generated by make_yamls.py" + (" --smoke" if smoke else "")] + reps + [f"output_csv: 23_overhead/{res}/{name}.csv", "", "applications:"]
            for app, source, binary, has_strided in apps:
                args = "{tasks} {elems} {buffers} 7 200" + (" {strided}" if has_strided else "")
                out += [f"  - name: {app}", f'    command: "hostname; {source}{prefix}{{env}} {BIN}/{binary} {args}"', "    parameters:",
                        "      env: [" + ", ".join(f'"{e}"' for e in envs) + "]", f"      tasks: [{tasks}]", f"      elems: [{elems}]", f"      buffers: [{buffers}]"]
                if has_strided:
                    out.append(f"      strided: [{', '.join(map(str, stridedvals))}]")
                out += ["    metrics:"] + [f'      {k}: "{x}"' for k, x in METRICS.items()]
                out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "overhead", variant: "{variant}", config: "{name}"}}', ""]
            open(os.path.join(HERE, sub, name + ".yaml"), "w").write("\n".join(out).rstrip() + "\n")
            names.append(f"23_overhead/{sub}/{name}.yaml")
        jobs = [[f"23_overhead/{sub}/{n}.yaml" for n in job] for job in JOBS[system]] if system in JOBS else [names]
        open(os.path.join(HERE, sub, "jobs.txt"), "w").write("".join(" ".join(job) + "\n" for job in jobs))
        if system == "gpuc4":
            open(os.path.join(HERE, sub, "chain.sh"), "w").write(
                f"#!/bin/sh\n# runs the overhead study{' smoke test' if smoke else ''} on gpuc4\ncd ~/finalizing-work/benchmarks\nmd5sum benchmark_wrapper.py\nfor f in " + " ".join(names) +
                "; do\n\tcsv=$(sed -n 's/^output_csv: //p' $f)\n\t[ -s \"$csv\" ] && continue\n\techo \"=== $f $(date +%H:%M)\"\n\ttimeout 3h python3 -u benchmark_wrapper.py $f | grep -E \"phase|Done|Error|Traceback\"\ndone\necho OVERHEAD-DONE $(date +%H:%M)\n")


if __name__ == "__main__":
    main()
