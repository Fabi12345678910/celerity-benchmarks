#!/usr/bin/env python3
"""Generates the YAMLs of the memcpy study (one contiguous copy host->device and device->host, programs in this folder) for gpuc4, ifi and LUMI:
one YAML per system with hip, opencl, plain SYCL on AdaptiveCpp and DPC++ (host memory pinned and pageable) and Celerity on both
(its own pinned host memory; contiguous copies never reach copylib). Size 4 B only (the per-copy overhead; the LUMI results also have 64 B .. 1 GiB from the first version), 30 copies per measurement.
Env: HSA_ENABLE_SDMA=0 (the standing base) and HSA_ENABLE_SDMA=1 as the reference, because the copy engine is part of the question.
Also writes <system>/memcpy_4b.yaml (2026-10-07): 4 B only, HIP pinned and Celerity on acpp / DPC++ with copylib on (defaults) and
off (CELERITY_COPYLIB=off), SDMA off, 10 iterations. jobs.txt lists memcpy_4b.yaml. Usage: python3 make_yamls.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ENVS = ["HSA_ENABLE_SDMA=0", "HSA_ENABLE_SDMA=1"]
SIZES = "4"  # only the per-copy overhead matters (2026-10-07); LUMI ran 4 B .. 1 GiB before that
DPCPP = ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && "
BIN = "~/finalizing-work/build/memcpy"
NUM = "([0-9.-]+)"


def metrics(celerity):
    m = {"machine": "^([^ \\n]+)"}
    labels = [("h2d", "H2D"), ("d2h", "D2H")]
    if celerity:
        labels += [("h2d_tasks", "H2D tasks"), ("h2d_base", "H2D base"), ("d2h_tasks", "D2H tasks"), ("d2h_base", "D2H base")]
    for key, label in labels:
        m[f"{key}_us"] = f"{label}: {NUM} us median"
        if key in ("h2d", "d2h"):
            m[f"{key}_min_us"] = f"{label}: [^,]*, {NUM} us min"
            m[f"{key}_gbps"] = f"{label}: [^,]*, [^,]*, {NUM} GB/s"
            m[f"{key}_stream_us"] = f"{label}: [^\\n]*stream {NUM} us/copy"
            m[f"{key}_submit_us"] = f"{label}: [^\\n]*submit {NUM} us/copy"
    m["check"] = "Check: ([a-zA-Z]+)"
    return m


# (application, source, binary, has host argument)
APPS = [("hip", "", "memcpy_hip", True), ("opencl", "", "memcpy_opencl", True), ("SYCL-acpp", "", "memcpy_acpp", True),
        ("SYCL-dpcpp", DPCPP, "memcpy_dpcpp", True), ("Celerity-acpp", "", "memcpy_celerity_acpp", False),
        ("Celerity-dpcpp", DPCPP, "memcpy_celerity_dpcpp0326", False)]


def main():
    for system in ("gpuc4", "ifi", "lumi"):
        os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
        prefix = "ROCR_VISIBLE_DEVICES=4 " if system == "lumi" else ""
        out = ["# generated by make_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 24_memcpy/{system}/results/memcpy.csv", "", "applications:"]
        for app, source, binary, has_host in APPS:
            args = "{bytes} 30" + (" {host}" if has_host else "")
            out += [f"  - name: {app}", f'    command: "hostname; {source}{prefix}{{env}} {BIN}/{binary} {args}"', "    parameters:",
                    "      env: [" + ", ".join(f'"{e}"' for e in ENVS) + "]", f"      bytes: [{SIZES}]"]
            if has_host:
                out.append("      host: [pinned, pageable]")
            out += ["    metrics:"] + [f"      {k}: '{x}'" for k, x in metrics(not has_host).items()]
            out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "memcpy"}}', ""]
        if system != "lumi":  # LUMI's memcpy.yaml is the version that ran (4 B .. 1 GiB)
            open(os.path.join(HERE, system, "memcpy.yaml"), "w").write("\n".join(out).rstrip() + "\n")
        for sdma, suffix in ((0, ""), (1, "_sdma1")):  # sdma1: the same runs with the SDMA engine on (2026-10-07)
            out = ["# generated by make_yamls.py", "iterations: 10", "warmup_iterations: 1", f"output_csv: 24_memcpy/{system}/results/memcpy_4b{suffix}.csv", "", "applications:"]
            for app, source, binary, has_host in APPS:
                if app in ("opencl", "SYCL-acpp", "SYCL-dpcpp"):
                    continue
                envs = [f"HSA_ENABLE_SDMA={sdma}"] + ([] if has_host else [f"HSA_ENABLE_SDMA={sdma} CELERITY_COPYLIB=off"])
                out += [f"  - name: {app}", f'    command: "hostname; {source}{prefix}{{env}} {BIN}/{binary} 4 30' + (' pinned' if has_host else '') + '"',
                        "    parameters:", "      env: [" + ", ".join(f'"{e}"' for e in envs) + "]", "    metrics:"]
                out += [f"      {k}: '{x}'" for k, x in metrics(not has_host).items()]
                out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "memcpy", bytes: 4}}', ""]
            open(os.path.join(HERE, system, f"memcpy_4b{suffix}.yaml"), "w").write("\n".join(out).rstrip() + "\n")
        open(os.path.join(HERE, system, "jobs.txt"), "w").write(f"24_memcpy/{system}/memcpy_4b.yaml\n")


if __name__ == "__main__":
    main()
