# Generates the row-width benchmark (strided_rows_transfer, build 014e21a). Run: python3 make_rows_yamls.py
#   <system>_rows.yaml   rows of S = 4 * W useful bytes with a pitch of 256 bytes (M = 64), i.e. 256 - S bytes not accessed between
#                        them: S = 32, 64, 128 (W = 8, 16, 32), plus S = 4 (the sparse case, M = 64 of 09_sparse/) and S = 256 (whole rows,
#                        contiguous: Celerity's regular path) as references. Host side strided, device side contiguous.
# Staging in the recommended configuration of the worker sweep (06_cores/) vs. the same plus COPYLIB_HOST_KERNEL=1. N up to 2^24 rows, so
# the host buffer (N * 256 bytes) stays at 4 GiB; useful data per copy up to 2^24 * S (512 MiB at S = 32, 2 GiB at S = 128).
# Results: 10_rows/results/<system>_rows.csv (paths relative to benchmarks/).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MiB = 1024 ** 2
SYSTEMS = {  # workers (one per core), prefix
    "gpuc4": ("8,10,12,14", ""),
    "ifi": ("5,6,7,0,8,9,10,11", ""),
    "lumi": ("5,6,7,9", "ROCR_VISIBLE_DEVICES=4"),
}
N = [2 ** i for i in range(14, 25, 2)]  # 16 Ki .. 16 Mi rows
M = 64  # row pitch: 256 bytes
W = [1, 8, 16, 32, 64]  # S = 4, 32, 64, 128, 256 bytes
METRICS = {
    "machine": "^(\\S+)",
    "buffer_creation_gbps": "buffer creation:.*?([0-9]+\\.[0-9]+)GB/s",
    "copy_bandwidth": "first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_only_gbps": "read only:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_write_gbps": "read write:.*?([0-9]+\\.[0-9]+)GB/s",
    "d2h_gbps": "device to host:.*?([0-9]+\\.[0-9]+)GB/s",
    "check": "Check: (\\w+)",
    "full_data_size_gib": "Data Size:\\s*([0-9.]+)\\s*GiB",
    "data_size_gib": "Worked on Data Size:\\s*([0-9.]+)\\s*GiB",
}
IMPLS = [("Celerity-acpp", "", "acpp"), ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ", "dpcpp0326")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    for system, (cpus, prefix) in SYSTEMS.items():
        n = cpus.count(",") + 1
        staging = (f"CELERITY_COPYLIB_QUEUES={n} CELERITY_COPYLIB_STAGING_BYTES={n * 4 * MiB} CELERITY_COPYLIB_CHUNK_BYTES={4 * MiB} "
                   f"COPYLIB_WORKER_CPUS={cpus} COPYLIB_PLAN_ORDER=dynamic")
        lines = ["# generated by make_rows_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 10_rows/results/{system}_rows.csv", "",
                 "applications:"]
        for app, source, impl in IMPLS:
            command = (f"hostname; {source}{prefix + ' ' if prefix else ''}{{env}} "
                       f"~/finalizing-work/build/bench-rows-{impl}-bench/strided_rows_transfer {{N}} {M} {{W}}")
            lines += [f"  - name: {app}", f"    command: {q(command)}", "    parameters:",
                      f"      env: [{q(staging)}, {q(staging + ' COPYLIB_HOST_KERNEL=1')}]",
                      f"      N: [{', '.join(map(str, N))}]", f"      W: [{', '.join(map(str, W))}]", "    metrics:"]
            lines += [f"      {k}: {q(v)}" for k, v in METRICS.items()]
            lines += ['    static: {celerity: "3dcopylib-bench 014e21a", program: "strided_rows_transfer", M: 64}', ""]
        os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
        with open(os.path.join(HERE, f"{system}_rows.yaml"), "w") as f:
            f.write("\n".join(lines).rstrip() + "\n")
        print(f"{system}_rows")


if __name__ == "__main__":
    main()
