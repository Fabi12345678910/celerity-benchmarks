#!/usr/bin/env python3
"""The last benchmark (2026-10-08): the default "lines" benchmark of the PUBLISHED Celerity (GitHub Fabi12345678910/celerity-runtime master
536d754, gpu3dcopylib GitHub main 843fafe), no sweep, on all four systems. strided_transfer, 4-byte rows, M = 1 (contiguous) and M = 2, N = 1..2^28:
  lines_<system>.yaml          the build's defaults (staging) and COPYLIB_HOST_KERNEL=1, as one env list (innermost: back to back per point)
  lines_native_<system>.yaml   CELERITY_COPYLIB=off (Celerity's own copy path); M = 2 only up to 2^23 rows on AMD (about 1 MB/s; NVIDIA all sizes), M = 1 all sizes
AMD systems: HSA_ENABLE_SDMA=0 (the standing base), AdaptiveCpp and DPC++; LUMI one GCD (ROCR_VISIBLE_DEVICES=4). NVIDIA: AdaptiveCpp (CUDA backend) only.
3 iterations + 1 warm-up. Writes <system>/<name>.yaml (results <system>/results/). Usage: python3 make_lines_yamls.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CELERITY = "celerity-runtime master 536d754 (published), gpu3dcopylib 843fafe"
DPCPP = ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && "
SYSTEMS = {"gpuc4": ("", [("acpp", ""), ("dpcpp0326", DPCPP)], "HSA_ENABLE_SDMA=0"),
           "ifi": ("", [("acpp", ""), ("dpcpp0326", DPCPP)], "HSA_ENABLE_SDMA=0"),
           "lumi": ("ROCR_VISIBLE_DEVICES=4 ", [("acpp", ""), ("dpcpp0326", DPCPP)], "HSA_ENABLE_SDMA=0"),
           "nvidia": ("", [("acpp-cuda", "")], "")}
FULL = [2 ** i for i in range(29)]
METRICS = {"machine": "^(\\\\S+)", "buffer_creation_gbps": "buffer creation:.*?([0-9]+\\\\.[0-9]+)GB/s",
           "copy_bandwidth": "first access.*?:.*?([0-9]+\\\\.[0-9]+)GB/s", "d2h_gbps": "device to host:.*?([0-9]+\\\\.[0-9]+)GB/s",
           "check": "Check: (\\\\w+)", "full_data_size_gib": "Data Size:\\\\s*([0-9.]+)\\\\s*GiB", "data_size_gib": "Worked on Data Size:\\\\s*([0-9.]+)\\\\s*GiB"}


def q(s):
    return '"' + s + '"'


def write(system, name, apps):
    lines = ["# generated by make_lines_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 26_published/{system}/results/{name}.csv", "", "applications:"]
    for app, src, prefix, impl, params, config in apps:
        path = f"~/finalizing-work/build/bench-transfer-{impl}-published/strided_transfer"
        lines += [f"  - name: {app}", f"    command: {q(f'hostname; {src}{prefix}{{env}} {path} {{N}} {{M}}')}", "    parameters:"]
        lines += [f"      {k}: [{', '.join(q(v) if isinstance(v, str) else str(v) for v in vals)}]" for k, vals in params.items()]
        lines += ["    metrics:"] + [f"      {k}: {q(v)}" for k, v in METRICS.items()]
        lines += ["    static: {" + f'celerity: "{CELERITY}", program: "strided_transfer", config: "{config}"' + "}", ""]
    os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
    open(os.path.join(HERE, system, f"{name}.yaml"), "w").write("\n".join(lines).rstrip() + "\n")


for system, (prefix, impls, sdma) in SYSTEMS.items():
    base = (sdma + " ").lstrip() if sdma else ""
    envs = [sdma or "CELERITY_COPYLIB=on", f"{base}COPYLIB_HOST_KERNEL=1"]
    native = f"{base}CELERITY_COPYLIB=off"
    write(system, f"lines_{system}", [(f"Celerity-{i.split('-')[0] if i != 'acpp-cuda' else 'acpp'}", s, prefix, i, {"N": FULL, "M": [1, 2], "env": envs}, "defaults_and_host_kernel")
                                      for i, s in impls])
    apps = []
    for i, s in impls:
        app = f"Celerity-{'acpp' if i.startswith('acpp') else 'dpcpp'}"
        apps.append((app, s, prefix, i, {"N": FULL, "M": [1], "env": [native]}, "native"))
        apps.append((app, s, prefix, i, {"N": FULL if system == "nvidia" else FULL[:24], "M": [2], "env": [native]}, "native"))  # NVIDIA native (CUDA 2D copies) is fast enough for all sizes
    write(system, f"lines_native_{system}", apps)
print("written")
