# Generates the worker/core sweep (celerity-bench 014e21a: fixed-width host copies with non-temporal pack stores). Run: python3 make_core_yamls.py
#
# One YAML per configuration in 06_cores/<system>/, writing 06_cores/<system>/results/<name>.csv (paths relative to benchmarks/, where the
# wrapper and job_bench.sbatch run). Every worker has its own physical core: Celerity's threads (CPUs 1-4) and hyper-threading
# siblings are never used. Chunks are 4 MiB and the staging is workers * 4 MiB, so only the worker count changes, not the chunks.
#   reference_base, reference_host_kernel   the sweep base so far (2 workers, block, 16 MiB chunks) and the host kernel on top of it
#   workers_<n>_<order>                       n workers on the n nearest free cores, chunks distributed block (fixed) or dynamic
#   place_<far|mixed|all>_<order>             4 workers on far cores, 2 near + 2 far, or COPYLIB_WORKER_CPUS=all
import os
import glob

HERE = os.path.dirname(os.path.abspath(__file__))
MiB = 1024 ** 2
CHUNK = 4 * MiB

SYSTEMS = {
    # free cores, nearest first; worker counts; far and mixed 4-worker placements; fixed prefix; the sweep base's worker CPUs
    "gpuc4": dict(cores=[8, 10, 12, 14, 6] + list(range(16, 24)),  # P-cores, then E-cores
                  counts=[1, 2, 3, 4, 5, 6, 8, 10, 13], far="16,17,18,19", mixed="8,10,16,17", prefix="", base_cpus="8,10"),
    "ifi": dict(cores=[5, 6, 7, 0] + list(range(8, 16)),  # Celerity's L3 group, then the other one
                counts=[1, 2, 3, 4, 6, 8, 10, 12], far="8,9,10,11", mixed="5,6,8,9", prefix="", base_cpus="5,6"),
    "lumi": dict(cores=[5, 6, 7] + list(range(9, 16)) + [c for g in range(16, 64, 8) for c in range(g + 1, g + 8)],  # GCD 4's CCD,
                 counts=[1, 2, 3, 4, 6, 8, 10, 16, 24, 32, 52],  # NUMA 0, then NUMA 1, 2, 3
                 far="49,50,51,52", mixed="5,6,49,50", prefix="ROCR_VISIBLE_DEVICES=4", base_cpus="5,6"),
}
ORDERS = {"block": "block", "dynamic": "dynamic"}  # block: worker i takes the i-th contiguous block of chunks (copylib's default)

N = [2 ** i for i in range(16, 29, 2)]  # 64 Ki .. 256 Mi rows (0.25 MiB .. 1 GiB per copy)
M = [2, 4]

METRICS = {
    "machine": "^(\\S+)",
    "buffer_creation_gbps": "buffer creation:.*?([0-9]+\\.[0-9]+)GB/s",
    "copy_bandwidth": "first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_only_gbps": "read only:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_write_gbps": "read write:.*?([0-9]+\\.[0-9]+)GB/s",
    "d2h_gbps": "device to host:.*?([0-9]+\\.[0-9]+)GB/s",
    "check": "Check: (\\w+)",
    "full_data_size_gib": "Data Size:\\s*([0-9.]+)\\s*GiB",
    "data_size_gib": "Worked on Data Size:\\s*([0-9.]+)\\s*GiB",
}
IMPLS = [("Celerity-acpp", "", "~/finalizing-work/build/bench-transfer-acpp-bench"),
         ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ",
          "~/finalizing-work/build/bench-transfer-dpcpp0326-bench")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def workers(n, cpus, order):
    return (f"CELERITY_COPYLIB_QUEUES={n} CELERITY_COPYLIB_STAGING_BYTES={n * CHUNK} CELERITY_COPYLIB_CHUNK_BYTES={CHUNK} "
            f"COPYLIB_WORKER_CPUS={cpus} COPYLIB_PLAN_ORDER={order}")


def configs(s):
    c = {"reference_base": f"COPYLIB_WORKER_CPUS={s['base_cpus']}",
         "reference_host_kernel": f"COPYLIB_WORKER_CPUS={s['base_cpus']} COPYLIB_HOST_KERNEL=1"}
    for n in s["counts"]:
        cpus = ",".join(map(str, s["cores"][:n]))
        for order in (["block"] if n == 1 else ORDERS):  # one worker: both orders are the same
            c[f"workers_{n:02d}" + ("" if n == 1 else f"_{order}")] = workers(n, cpus, order)
    for place in ("far", "mixed", "all"):
        for order in ORDERS:
            c[f"place_{place}_{order}"] = workers(4, s.get(place, "all"), order)
    return c


def write(system, name, env, prefix):
    lines = ["# generated by make_core_yamls.py", "iterations: 3", "warmup_iterations: 1",
             f"output_csv: 06_cores/{system}/results/{name}.csv", "", "applications:"]
    for app, source, binary in IMPLS:
        lines += [f"  - name: {app}",
                  f"    command: {q('hostname; ' + source + (prefix + ' ' if prefix else '') + '{env} ' + binary + '/strided_transfer {N} {M}')}",
                  "    parameters:",
                  f"      env: [{q(env)}]",
                  f"      N: [{', '.join(map(str, N))}]",
                  f"      M: [{', '.join(map(str, M))}]",
                  "    metrics:"]
        lines += [f"      {k}: {q(v)}" for k, v in METRICS.items()]
        lines += ['    static: {celerity: "3dcopylib-bench 014e21a"' + (f", prefix: {q(prefix)}" if prefix else "") + "}", ""]
    os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
    with open(os.path.join(HERE, system, name + ".yaml"), "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")


def main():
    for old in glob.glob(os.path.join(HERE, "*", "*.yaml")):
        os.remove(old)
    for system, s in SYSTEMS.items():
        c = configs(s)
        for name, env in c.items():
            write(system, name, env, s["prefix"])
        print(f"{system}: {len(c)} configurations")


if __name__ == "__main__":
    main()
