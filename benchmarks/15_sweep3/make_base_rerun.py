#!/usr/bin/env python3
"""Reruns of the sweep 3 bases (strided and block, staging and host kernel; the native block copy is not rerun), because the single base run of
each variant was skewed by node and time (on ifi and LUMI the bases ran on different nodes). Each rerun is the base YAML unchanged (full grid,
same env) with the config renamed to <program>_<stg|hk>_rerun_r<k>. REPEATS reruns per system: gpuc4 one after another, ifi on the nodes
the original bases ran on (gc20, gc22, gc26), LUMI as separate jobs. plot_overview.py --ref=rerun uses their median as the reference.
Usage: python3 make_base_rerun.py ; writes <system>/*_rerun_r<k>.yaml, gpuc4/rerun_chain.sh, <system>/rerun_jobs.txt"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASES = ["strided_stg", "strided_hk", "block_stg", "block_hk"]
REPEATS = 3
IFI_NODES = ["gc20", "gc22", "gc26"]


def main():
    for system in ("gpuc4", "ifi", "lumi"):
        jobs, chain = [], []
        for k in range(1, REPEATS + 1):
            names = []
            for b in BASES:
                s = open(os.path.join(HERE, system, f"{b}_base.yaml")).read()
                new = f"{b}_rerun_r{k}"
                s = s.replace(f"results/{b}_base.csv", f"results/{new}.csv").replace(f'config: "{b}_base", option: "base"', f'config: "{new}", option: "rerun"')
                assert new in s and s.count("rerun") >= 3
                open(os.path.join(HERE, system, new + ".yaml"), "w").write(s.replace("# generated by make_sweep3_yamls.py", "# generated by make_base_rerun.py"))
                names.append(f"15_sweep3/{system}/{new}.yaml")
            node = IFI_NODES[k - 1] if system == "ifi" else "-"
            jobs.append(f"{node} " + " ".join(names))
            chain += names
        open(os.path.join(HERE, system, "rerun_jobs.txt"), "w").write("\n".join(jobs) + "\n")
        if system == "gpuc4":
            open(os.path.join(HERE, system, "rerun_chain.sh"), "w").write(
                "#!/bin/sh\n# runs the base reruns one after another (gpuc4)\ncd ~/finalizing-work/benchmarks\nmd5sum benchmark_wrapper.py\nfor f in " + " ".join(chain) +
                "; do\n\tcsv=$(sed -n 's/^output_csv: //p' $f)\n\t[ -s \"$csv\" ] && continue\n\techo \"=== $f $(date +%H:%M)\"\n\ttimeout 3h python3 -u benchmark_wrapper.py $f | grep -E \"phase|Done|Error|Traceback\"\ndone\necho RERUN-DONE $(date +%H:%M)\n")


if __name__ == "__main__":
    main()
