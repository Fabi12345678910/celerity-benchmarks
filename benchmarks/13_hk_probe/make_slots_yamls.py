# Generates the check of the proposed copylib change (one launch per row slot of a 64-byte line, device -> host) on all three systems:
# does it help on gpuc4 and leave ifi (APU) and LUMI (Infinity Fabric) unharmed? Run: python3 make_slots_yamls.py
#
# hk_probe device -> host writes, three orders per shape and size:
#   natural  copylib today: one launch, consecutive work items take consecutive rows
#   filter   the proposed diff: (62 + S) / P + 1 launches over the whole grid when S < P < 64, each writing only its slot's rows
#   phase    the compact variant: 64 / P launches, each covering only its own rows
# Shapes (row width S / pitch P / access width E in bytes): every S < P < 64 class (the change applies), plus P = 64 and 256 as
# controls (one launch, nothing changes). Sizes 16k, 256k and 2M rows: small copies show the cost of the extra launches.
# 5 runs + 1 warmup each; hk_probe reports the median of 5 in-process repetitions per run.
# Output: 13_hk_probe/<system>_slots.yaml writing 13_hk_probe/results/<system>_slots.csv (paths relative to benchmarks/).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PROBE = "~/finalizing-work/benchmarks/13_hk_probe/hk_probe"
SYSTEMS = {"gpuc4": "taskset -c 8", "ifi": "taskset -c 5", "lumi": "ROCR_VISIBLE_DEVICES=4 taskset -c 5"}
SHAPES = [(4, 8, 4), (4, 12, 4), (4, 16, 4), (4, 24, 4), (4, 32, 4), (4, 48, 4), (8, 16, 8), (8, 32, 8), (16, 32, 16), (16, 48, 16),
          (32, 48, 16), (4, 64, 4), (4, 256, 4)]
ROWS = [16384, 262144, 2097152]
ORDERS = ["natural", "filter", "phase"]
METRICS = {"machine": "^(\\S+)", "gbps": "probe: ([0-9.]+)GB/s", "mrows_per_s": "rows/s=([0-9.]+)M", "check": "check=(\\w+)",
           "device": "device=(\\S+)"}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    for system, prefix in SYSTEMS.items():
        lines = ["# generated by make_slots_yamls.py", "iterations: 5", "warmup_iterations: 1", f"output_csv: 13_hk_probe/results/{system}_slots.csv",
                 "", "applications:"]
        for s, p, e in SHAPES:
            lines += [f"  - name: w_s{s}_p{p}", f"    command: {q(f'hostname; {prefix} {PROBE} w {s} {p} {e} {{rows}} default {{order}} 5')}",
                      "    parameters:", f"      rows: [{', '.join(map(str, ROWS))}]", f"      order: [{', '.join(q(o) for o in ORDERS)}]",
                      "    metrics:"]
            lines += [f"      {k}: {q(v)}" for k, v in METRICS.items()]
            lines += [f"    static: {{study: \"slots\", S: {s}, P: {p}, E: {e}}}", ""]
        with open(os.path.join(HERE, f"{system}_slots.yaml"), "w") as f:
            f.write("\n".join(lines).rstrip() + "\n")
    print(f"{len(SHAPES) * len(ROWS) * len(ORDERS)} configurations per system")


if __name__ == "__main__":
    main()
