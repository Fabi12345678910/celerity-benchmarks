# Generates the gpuc4 host-kernel slowdown study (13_hk_probe/): when is COPYLIB_HOST_KERNEL=1 slow on PCIe, and why.
# Run: python3 make_hk_probe_yamls.py
#
# hk_probe (hk_probe.hip, no Celerity or copylib) copies rows of S bytes at a pitch of P bytes between device memory and pinned host
# memory with E-byte accesses, in different orders (see hk_probe.hip). Groups:
#   w_pitch      device -> host, 4-byte rows, pitch 8 .. 1024 B, copylib's order (natural)
#   w_fix        the same at pitch 8 .. 48 B with the three orders that avoid repeated partial writes to one 64-byte line in a kernel:
#                phase (one launch per row slot of a line), spread (same-line rows far apart), rmw (read + write whole 16-byte pieces)
#   w_size       4-byte rows at pitch 8 B: natural / phase / rmw over the copy size
#   w_distance   4-byte rows at pitch 8 B: same-line writes D elements apart (the window in which a repeated partial write is slow)
#   w_width      row widths 4 .. 128 B at pitch 256 B (cost per row, not per byte)
#   w_s16        16-byte rows at pitch 32 B: natural / phase / rmw
#   r_pitch      host -> device, 4-byte rows, pitch 8 .. 1024 B
#   contiguous   4-byte accesses with P = S (both directions), the link reference
# Celerity (strided_transfer, acpp, 014e21a), the same shapes through the real stack:
#   celerity_hk       COPYLIB_HOST_KERNEL=1, copylib's defaults (the defaults sweep's hk_base)
#   celerity_staging  the staging configuration recommended by the worker sweep
# 10 runs + 1 warmup each; hk_probe reports the median of 5 in-process repetitions per run.
# Output: 13_hk_probe/gpuc4_hk_probe.yaml writing 13_hk_probe/results/gpuc4_hk_probe.csv (paths relative to benchmarks/).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PROBE = "~/finalizing-work/benchmarks/13_hk_probe/hk_probe"
TRANSFER = "~/finalizing-work/build/bench-transfer-acpp-bench/strided_transfer"
PROBE_METRICS = {"machine": "^(\\S+)", "gbps": "probe: ([0-9.]+)GB/s", "mrows_per_s": "rows/s=([0-9.]+)M", "check": "check=(\\w+)"}
CELERITY_METRICS = {
    "machine": "^(\\S+)",
    "copy_bandwidth": "first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
    "d2h_gbps": "device to host:.*?([0-9]+\\.[0-9]+)GB/s",
    "check": "Check: (\\w+)",
}
HK = "COPYLIB_WORKER_CPUS=8,10 COPYLIB_HOST_KERNEL=1"
STAGING = ("CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_STAGING_BYTES=16777216 CELERITY_COPYLIB_CHUNK_BYTES=4194304 "
           "COPYLIB_WORKER_CPUS=8,10,12,14 COPYLIB_PLAN_ORDER=dynamic")

# name: (dir, S, P, E, rows, order) value lists; host memory stays below 512 MiB per run
PROBE_GROUPS = {
    "w_pitch": dict(dir=["w"], S=[4], P=[8, 12, 16, 24, 32, 48, 64, 128, 256], E=[4], rows=[2097152], order=["natural"]),
    "w_pitch_far": dict(dir=["w"], S=[4], P=[1024], E=[4], rows=[524288], order=["natural"]),
    "w_fix": dict(dir=["w"], S=[4], P=[8, 16, 32, 48], E=[4], rows=[2097152], order=["phase", "spread", "rmw"]),
    "w_size": dict(dir=["w"], S=[4], P=[8], E=[4], rows=[16384, 262144, 4194304], order=["natural", "phase", "rmw"]),
    "w_distance": dict(dir=["w"], S=[4], P=[8], E=[4], rows=[16777216], order=["d16384", "d32768", "d49152", "d65536"]),
    "w_width": dict(dir=["w"], S=[4, 8, 16, 32, 64, 128], P=[256], E=[4], rows=[1048576], order=["natural"]),
    "w_s16": dict(dir=["w"], S=[16], P=[32], E=[16], rows=[2097152], order=["natural", "phase"]),
    "w_s16_rmw": dict(dir=["w"], S=[16], P=[32], E=[4], rows=[2097152], order=["rmw"]),
    "r_pitch": dict(dir=["r"], S=[4], P=[8, 16, 32, 64, 128, 256], E=[4], rows=[1048576], order=["natural"]),
    "r_pitch_far": dict(dir=["r"], S=[4], P=[1024], E=[4], rows=[524288], order=["natural"]),
    "contiguous": dict(dir=["w", "r"], S=[4], P=[4], E=[4], rows=[16777216], order=["natural"]),
}
# strided_transfer: column 0 of an N x M int buffer = 4-byte rows, pitch 4 * M bytes
CELERITY = dict(N=[1048576, 16777216], M=[2, 4, 8, 16, 64])


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def values(v):
    return "[" + ", ".join(q(x) if isinstance(x, str) else str(x) for x in v) + "]"


def main():
    lines = ["# generated by make_hk_probe_yamls.py", "iterations: 10", "warmup_iterations: 1",
             "output_csv: 13_hk_probe/results/gpuc4_hk_probe.csv", "", "applications:"]
    for name, p in PROBE_GROUPS.items():
        lines += [f"  - name: {name}", f"    command: {q(f'hostname; taskset -c 8 {PROBE} {{dir}} {{S}} {{P}} {{E}} {{rows}} default {{order}} 5')}",
                  "    parameters:"]
        lines += [f"      {k}: {values(v)}" for k, v in p.items()]
        lines.append("    metrics:")
        lines += [f"      {k}: {q(v)}" for k, v in PROBE_METRICS.items()]
        lines += ["    static: {study: \"hk_probe\", tool: \"hk_probe\"}", ""]
    for name, env in (("celerity_hk", HK), ("celerity_staging", STAGING)):
        lines += [f"  - name: {name}", f"    command: {q(f'hostname; {env} {TRANSFER} {{N}} {{M}}')}", "    parameters:"]
        lines += [f"      {k}: {values(v)}" for k, v in CELERITY.items()]
        lines.append("    metrics:")
        lines += [f"      {k}: {q(v)}" for k, v in CELERITY_METRICS.items()]
        lines += ["    static: {study: \"hk_probe\", tool: \"Celerity-acpp\", celerity: \"3dcopylib-bench 014e21a\"}", ""]
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, "gpuc4_hk_probe.yaml"), "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    runs = 0
    for p in PROBE_GROUPS.values():
        n = 1
        for v in p.values():
            n *= len(v)
        runs += n
    runs += 2 * len(CELERITY["N"]) * len(CELERITY["M"])
    print(f"gpuc4_hk_probe.yaml: {runs} configurations x 11 runs")


if __name__ == "__main__":
    main()
