# Generates the hardware-limit benchmarks (membw.cpp, linkbw.hip) per system. Run: python3 make_limits_yamls.py
#   <system>_membw.yaml       host memory bandwidth of every access pattern over the thread count (each thread on its own core)
#   <system>_linkbw.yaml      DMA copies and host-memory kernel accesses, 1 MiB .. 1 GiB, SDMA on and off
#   <system>_concurrent.yaml  DMA copy of 1 GiB while 2, 4 or 8 CPU threads run the staging pack/unpack loop (memory shared by both)
# Results: 07_limits/results/<name>.csv (paths relative to benchmarks/, where the wrapper runs).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BIN = "~/finalizing-work/benchmarks/limits"

# cores in the order of the worker sweep (06_cores/make_core_yamls.py): nearest free cores first, never CPUs 1-4 or SMT siblings
SYSTEMS = {
    "gpuc4": dict(cores=[8, 10, 12, 14, 6] + list(range(16, 24)), counts=[1, 2, 3, 4, 5, 6, 8, 10, 13], extra=[],
                  load=["8,10", "8,10,12,14", "8,10,12,14,6,16,17,18"], prefix="taskset -c 1"),
    "ifi": dict(cores=[5, 6, 7, 0] + list(range(8, 16)), counts=[1, 2, 3, 4, 6, 8, 10, 12], extra=["8,9,10,11", "5,6,8,9"],
                load=["5,6", "5,6,8,9", "5,6,7,0,8,9,10,11"], prefix="taskset -c 1"),
    "lumi": dict(cores=[5, 6, 7] + list(range(9, 16)) + [c for g in range(16, 64, 8) for c in range(g + 1, g + 8)],
                 counts=[1, 2, 3, 4, 6, 8, 10, 16, 24, 52], extra=[], local_counts=[1, 2, 4, 10, 24, 52],
                 load=["5,6", "5,6,7,9", "5,6,7,9,10,11,12,13"], prefix="ROCR_VISIBLE_DEVICES=4 taskset -c 1"),
}
MEMBW_TESTS = ["read", "write", "write_nt", "copy", "copy_nt", "pack2", "pack4", "unpack2", "unpack4"]
LINKBW_TESTS = ["dma_h2d", "dma_d2h", "dma_bidir", "kernel_read", "kernel_write", "kernel_read_s2", "kernel_read_s4", "kernel_write_s2",
                "kernel_write_s4"]
MIB = [1, 4, 16, 64, 256, 1024]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def flow(values):
    return "[" + ", ".join(q(v) if isinstance(v, str) else str(v) for v in values) + "]"


def app(name, command, params, metrics):
    lines = [f"  - name: {name}", f"    command: {q(command)}", "    parameters:"]
    lines += [f"      {k}: {flow(v)}" for k, v in params.items()]
    lines.append("    metrics:")
    lines += [f"      {k}: {q(v)}" for k, v in {"machine": "^(\\S+)", **metrics}.items()]
    return lines + [""]


def write(name, apps):
    lines = ["# generated by make_limits_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 07_limits/results/{name}.csv", "",
             "applications:"]
    for a in apps:
        lines += a
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, name + ".yaml"), "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(name)


def main():
    membw_metrics = {"useful_gbps": "useful: ([0-9.]+)GB/s", "memory_gbps": "memory: ([0-9.]+)GB/s"}
    link_metrics = {"gbps": "(?:dma|kernel)\\w*: ([0-9.]+)GB/s", "load_gbps": "load: ([0-9.]+)GB/s"}
    for system, s in SYSTEMS.items():
        lists = [",".join(map(str, s["cores"][:n])) for n in s["counts"]] + s["extra"]
        apps = [app("membw", f"hostname; {BIN}/membw {{test}} {{cpus}} {{place}} 64 5",
                    {"test": MEMBW_TESTS, "cpus": lists, "place": ["first" if system == "lumi" else "local"]}, membw_metrics)]
        if system == "lumi":  # also each thread on its own NUMA node's memory (the whole socket)
            local = [",".join(map(str, s["cores"][:n])) for n in s["local_counts"]]
            apps.append(app("membw-local", f"hostname; {BIN}/membw {{test}} {{cpus}} local 64 5",
                            {"test": MEMBW_TESTS, "cpus": local}, membw_metrics))
        write(f"{system}_membw", apps)
        write(f"{system}_linkbw", [app("linkbw", f"hostname; {{env}} {s['prefix']} {BIN}/linkbw {{test}} {{mib}} 5",
                                       {"env": ["", "HSA_ENABLE_SDMA=0"], "test": LINKBW_TESTS, "mib": MIB}, link_metrics)])
        loads = [f"{k}:{c}" for c in s["load"] for k in ("pack2", "pack4", "unpack2", "unpack4")]
        write(f"{system}_concurrent", [app("linkbw-concurrent", f"hostname; {s['prefix']} {BIN}/linkbw {{test}} 1024 5 {{load}}",
                                           {"test": ["dma_h2d", "dma_d2h"], "load": loads}, link_metrics)])


if __name__ == "__main__":
    main()
