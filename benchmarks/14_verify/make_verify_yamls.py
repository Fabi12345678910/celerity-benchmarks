#!/usr/bin/env python3
# Verification of the new defaults (Celerity 3dcopylib-bench 2dda28f): the old defaults, emulated with environment variables on the new
# build, against the new defaults, both variants, all three programs, both SYCL implementations.
#
# Configs (env on top of the build's defaults):
#   staging_old       Celerity's defaults before 2dda28f: 2 queues (16 MiB chunks), workers inherit the executor's core, block order,
#                     no kernel preload, 64-byte kernel elements
#   staging_new       the new defaults, nothing set: 8 queues (4 MiB chunks), workers on all CPUs, dynamic order, preload, 16-byte elements
#   staging_new_pin   the new defaults, the 8 workers pinned to dedicated cores (the worker sweep's placement)
#   staging_sweep2    sweep 2's staging base exactly (4 workers, 8 on ifi, pinned, 4 MiB chunks, dynamic): ties these results to sweep 2
#   hk_old            host kernel with the old defaults (2 queues, 16 MiB chunks, inherited workers, block, no preload, 64-byte elements)
#   hk_new            host kernel with the new defaults (2 queues, 16 MiB chunks, preload, 16-byte elements)
#   hk_new_me8        hk_new with COPYLIB_MAX_ELEM_SIZE=8 (8 vs 16 was a tie in sweep 2)
#   hk_new_wg16       hk_new with COPYLIB_WG_SIZE=16 (does work-group 16 still help DPC++ on gpuc4 with 16-byte elements?)
# Programs: strided_transfer (4-byte rows, pitch 8/16 B), strided_rows_transfer (4/32/128-byte rows, pitch 256 B),
#           strided_both_transfer (strided on host and device, pitch 8/16/64 B: staging also runs a copylib kernel here).
# One YAML per system, program and implementation; the configs alternate inside every iteration, so old and new share node and time.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MiB = 1 << 20
SYSTEMS = {
    "gpuc4": dict(pin8="8,10,12,14,6,16,17,18", sweep2=(4, "8,10,12,14"), prefix=""),
    "ifi": dict(pin8="5,6,7,0,8,9,10,11", sweep2=(8, "5,6,7,0,8,9,10,11"), prefix=""),
    "lumi": dict(pin8="5,6,7,9,10,11,12,13", sweep2=(4, "5,6,7,9"), prefix="ROCR_VISIBLE_DEVICES=4 "),
}
OLD = "COPYLIB_WORKER_CPUS=inherit COPYLIB_PLAN_ORDER=block COPYLIB_PRELOAD_KERNELS=0 COPYLIB_MAX_ELEM_SIZE=64"
PROGRAMS = {
    "transfer": dict(binary="bench-transfer-{}-bench/strided_transfer", args="{N} {M}", N=[2 ** i for i in range(16, 29, 2)], M=[2, 4]),
    "rows": dict(binary="bench-rows-{}-bench/strided_rows_transfer", args="{N} 64 {W}", N=[2 ** i for i in range(14, 25, 2)], W=[1, 8, 32]),
    "both": dict(binary="bench-both_strided-{}-bench/strided_both_transfer", args="{N} {M}", N=[2 ** i for i in range(16, 25, 2)], M=[2, 4, 16]),
}
IMPLS = {"acpp": ("Celerity-acpp", ""), "dpcpp0326": ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ")}
METRICS = {
    "machine": r"^(\S+)", "buffer_creation_gbps": r"buffer creation:.*?([0-9]+\.[0-9]+)GB/s", "copy_bandwidth": r"first access.*?:.*?([0-9]+\.[0-9]+)GB/s",
    "read_only_gbps": r"read only:.*?([0-9]+\.[0-9]+)GB/s", "read_write_gbps": r"read write:.*?([0-9]+\.[0-9]+)GB/s",
    "d2h_gbps": r"device to host:.*?([0-9]+\.[0-9]+)GB/s", "check": r"Check: (\w+)",
}


def configs(s):
    n, cpus = s["sweep2"]
    return {
        "staging_old": f"CELERITY_COPYLIB_QUEUES=2 {OLD}",
        "staging_new": "",
        "staging_new_pin": f"COPYLIB_WORKER_CPUS={s['pin8']}",
        "staging_sweep2": f"CELERITY_COPYLIB_QUEUES={n} CELERITY_COPYLIB_STAGING_BYTES={n * 4 * MiB} CELERITY_COPYLIB_CHUNK_BYTES={4 * MiB} "
                          f"COPYLIB_WORKER_CPUS={cpus} COPYLIB_PLAN_ORDER=dynamic COPYLIB_PRELOAD_KERNELS=0 COPYLIB_MAX_ELEM_SIZE=64",
        "hk_old": f"COPYLIB_HOST_KERNEL=1 {OLD}",
        "hk_new": "COPYLIB_HOST_KERNEL=1",
        "hk_new_me8": "COPYLIB_HOST_KERNEL=1 COPYLIB_MAX_ELEM_SIZE=8",
        "hk_new_wg16": "COPYLIB_HOST_KERNEL=1 COPYLIB_WG_SIZE=16",
    }


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    for system, s in SYSTEMS.items():
        os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
        for prog, p in PROGRAMS.items():
            for impl, (app, source) in IMPLS.items():
                name = f"{system}_{prog}_{impl}"
                lines = ["# generated by make_verify_yamls.py", "iterations: 5", "warmup_iterations: 1", f"output_csv: 14_verify/results/{name}.csv", "",
                         "applications:"]
                for cfg, env in configs(s).items():
                    # env comes first, then the size: the wrapper runs each iteration over all configs, so they alternate in time
                    command = f"hostname; {source}{s['prefix']}{env + ' ' if env else ''}~/finalizing-work/build/{p['binary'].format(impl)} {p['args']}"
                    lines += [f"  - name: {app}", f"    command: {q(command)}", "    parameters:"]
                    lines += [f"      {k}: [{', '.join(map(str, p[k]))}]" for k in ("N", "M", "W") if k in p]
                    lines += ["    metrics:"] + [f"      {k}: {q(v)}" for k, v in METRICS.items()]
                    lines += ["    static: {" + f"celerity: \"3dcopylib-bench 2dda28f\", program: \"{p['binary'].split('/')[1]}\", config: \"{cfg}\", "
                              f"variant: \"{'host kernel' if cfg.startswith('hk') else 'staging'}\", env: {q(env)}" + "}", ""]
                with open(os.path.join(HERE, f"{name}.yaml"), "w") as f:
                    f.write("\n".join(lines))
                print(name)


if __name__ == "__main__":
    main()
