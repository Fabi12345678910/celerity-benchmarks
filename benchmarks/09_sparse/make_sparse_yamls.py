# Generates the sparse and both-strided benchmarks (build 014e21a). Run: python3 make_sparse_yamls.py
#   <system>_sparse.yaml  strided_transfer with very sparse rows: one 4-byte value per row of 64 / 128 / 256 bytes (gaps of 60 / 124 /
#                         252 bytes, M = 16 / 32 / 64); host side strided, device side contiguous
#   <system>_both.yaml    strided_both_transfer (08_both_strided/): the same column copies, strided on the host AND the device side,
#                         M = 2 / 4 / 16 / 32 / 64
# Both compare staging in the recommended configuration of the worker sweep (06_cores/: dynamic chunk order, 4 MiB chunks, the best
# worker cores per system) with the host kernel (the same settings plus COPYLIB_HOST_KERNEL=1). N up to 2^24 rows, so the host
# buffer (N * M * 4 bytes) stays at most 4 GiB. Results: 09_sparse/results/<name>.csv (paths relative to benchmarks/).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MiB = 1024 ** 2
SYSTEMS = {  # workers (one per core), prefix
    "gpuc4": ("8,10,12,14", ""),
    "ifi": ("5,6,7,0,8,9,10,11", ""),
    "lumi": ("5,6,7,9", "ROCR_VISIBLE_DEVICES=4"),
}
N = [2 ** i for i in range(16, 25, 2)]  # 64 Ki .. 16 Mi rows
METRICS = {
    "machine": "^(\\S+)",
    "buffer_creation_gbps": "buffer creation:.*?([0-9]+\\.[0-9]+)GB/s",
    "copy_bandwidth": "first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_only_gbps": "read only:.*?([0-9]+\\.[0-9]+)GB/s",
    "read_write_gbps": "read write:.*?([0-9]+\\.[0-9]+)GB/s",
    "d2h_gbps": "device to host:.*?([0-9]+\\.[0-9]+)GB/s",
    "check": "Check: (\\w+)",
    "full_data_size_gib": "Data Size:\\s*([0-9.]+)\\s*GiB",
    "data_size_gib": "Worked on Data Size:\\s*([0-9.]+)\\s*GiB",
}
IMPLS = [("Celerity-acpp", "", "acpp"), ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ", "dpcpp0326")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(system, name, program, build, ms, ns=N, impls=None):
    cpus, prefix = SYSTEMS[system]
    n = cpus.count(",") + 1
    staging = (f"CELERITY_COPYLIB_QUEUES={n} CELERITY_COPYLIB_STAGING_BYTES={n * 4 * MiB} CELERITY_COPYLIB_CHUNK_BYTES={4 * MiB} "
               f"COPYLIB_WORKER_CPUS={cpus} COPYLIB_PLAN_ORDER=dynamic")
    lines = ["# generated by make_sparse_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 09_sparse/results/{system}_{name}.csv", "",
             "applications:"]
    for app, source, impl in [i for i in IMPLS if impls is None or i[2] in impls]:
        command = f"hostname; {source}{prefix + ' ' if prefix else ''}{{env}} ~/finalizing-work/build/{build}-{impl}-bench/{program} {{N}} {{M}}"
        lines += [f"  - name: {app}", f"    command: {q(command)}", "    parameters:",
                  f"      env: [{q(staging)}, {q(staging + ' COPYLIB_HOST_KERNEL=1')}]",
                  f"      N: [{', '.join(map(str, ns))}]", f"      M: [{', '.join(map(str, ms))}]", "    metrics:"]
        lines += [f"      {k}: {q(v)}" for k, v in METRICS.items()]
        lines += [f'    static: {{celerity: "3dcopylib-bench 014e21a", program: "{program}"}}', ""]
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, f"{system}_{name}.yaml"), "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"{system}_{name}")


def main():
    for system in SYSTEMS:
        write(system, "sparse", "strided_transfer", "bench-transfer", [16, 32, 64])
        write(system, "both", "strided_both_transfer", "bench-both_strided", [2, 4, 16, 32, 64])
        # rerun of the DPC++ runs that crashed in the untimed setup kernel (N * M >= 2^28, fixed by a 1D launch)
        write(system, "both_dpcpp64", "strided_both_transfer", "bench-both_strided", [64], ns=[2 ** 22, 2 ** 24], impls=["dpcpp0326"])


if __name__ == "__main__":
    main()
