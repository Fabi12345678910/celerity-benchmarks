#!/usr/bin/env python3
"""Generates the YAMLs of the SDMA study: the current defaults (2dda28f, nothing set) with and without HSA_ENABLE_SDMA=0, strided_transfer, AdaptiveCpp,
M = 1 (contiguous, native path) and M = 2 (copylib), N 1..2^28, for staging and host kernel (COPYLIB_HOST_KERNEL=1) on gpuc4, ifi and LUMI.
Both settings are one parameter list in one YAML with the env innermost, so they run back to back on the same node and drift cancels. ifi jobs are
pinned to the node of the corresponding sweep 3 defaults run (staging gc20, host kernel gc22), LUMI cannot be pinned.
Usage: python3 make_yamls.py ; writes <system>/strided_<stg|hk>_sdma.yaml, gpuc4/chain.sh, <system>/jobs.txt (ifi, LUMI)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NS = ", ".join(str(2 ** i) for i in range(29))
VARIANTS = {"stg": ("staging", ""), "hk": ("host kernel", "COPYLIB_HOST_KERNEL=1")}
IFI_NODE = {"stg": "gc20", "hk": "gc22"}
METRICS = {"machine": r"^(\\S+)", "buffer_creation_gbps": r"buffer creation:.*?([0-9]+\\.[0-9]+)GB/s", "copy_bandwidth": r"first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
           "read_only_gbps": r"read only:.*?([0-9]+\\.[0-9]+)GB/s", "read_write_gbps": r"read write:.*?([0-9]+\\.[0-9]+)GB/s",
           "d2h_gbps": r"device to host:.*?([0-9]+\\.[0-9]+)GB/s", "check": r"Check: (\\w+)", "full_data_size_gib": r"Data Size:\\s*([0-9.]+)\\s*GiB",
           "data_size_gib": r"Worked on Data Size:\\s*([0-9.]+)\\s*GiB"}


def main():
    for system in ("gpuc4", "ifi", "lumi"):
        os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
        prefix = "ROCR_VISIBLE_DEVICES=4 " if system == "lumi" else ""
        names, jobs = [], []
        for v, (vname, base) in VARIANTS.items():
            name = f"strided_{v}_sdma"
            envs = [base, (base + " HSA_ENABLE_SDMA=0").strip()]
            out = ["# generated by make_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 20_sdma_defaults/{system}/results/{name}.csv", "", "applications:",
                   "  - name: Celerity-acpp", f'    command: "hostname; {prefix}{{env}} ~/finalizing-work/build/bench-transfer-acpp-bench/strided_transfer {{N}} {{M}}"',
                   "    parameters:", f"      N: [{NS}]", "      M: [1, 2]", "      env: [" + ", ".join(f'"{e}"' for e in envs) + "]", "    metrics:"]
            out += [f'      {k}: "{x}"' for k, x in METRICS.items()]
            out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "strided_transfer", variant: "{vname}", config: "{name}"}}']
            open(os.path.join(HERE, system, name + ".yaml"), "w").write("\n".join(out) + "\n")
            names.append(f"20_sdma_defaults/{system}/{name}.yaml")
            jobs.append(f"{IFI_NODE[v] if system == 'ifi' else '-'} {names[-1]}")
        if system == "gpuc4":
            open(os.path.join(HERE, system, "chain.sh"), "w").write(
                "#!/bin/sh\n# runs the SDMA study on gpuc4\ncd ~/finalizing-work/benchmarks\nmd5sum benchmark_wrapper.py\nfor f in " + " ".join(names) +
                "; do\n\techo \"=== $f $(date +%H:%M)\"\n\ttimeout 3h python3 -u benchmark_wrapper.py $f | grep -E \"phase|Done|Error|Traceback\"\ndone\necho SDMA-DONE $(date +%H:%M)\n")
        elif system == "ifi":
            open(os.path.join(HERE, system, "jobs.txt"), "w").write("\n".join(jobs) + "\n")
        else:
            open(os.path.join(HERE, system, "jobs.txt"), "w").write("- " + " ".join(names) + "\n")


if __name__ == "__main__":
    main()
