#!/usr/bin/env python3
"""Generates the YAMLs of the preload study (COPYLIB_PRELOAD_KERNELS 1 vs 0) for gpuc4, ifi and LUMI.
Question: does the kernel preload make the whole program faster, or only the measured copy? And what does it cost where no kernel is used
(staging)? The earlier pair (15_sweep3 host kernel base vs preload_off) ran on different nodes on ifi and had no staging pair.
Design: one YAML per system holds all four variants (staging / host kernel x preload 1 / 0), so they run on the same node in the same job; the
wrapper's iterations are the outer loop and the env is the innermost parameter, so on and off run back to back at each point and drift
cancels. Programs: strided_transfer with M = 2 (strided: copylib runs) and M = 1 (contiguous: copylib never runs, the program only pays the
startup), N = 1 (pure startup) .. 2^24. The process wall time is the wrapper's runtime_sec. ifi also gets a second YAML (other node, reversed order).
Usage: python3 make_preload_yamls.py ; writes <system>/preload*.yaml, <system>/chain.sh (gpuc4) and <system>/jobs.txt (ifi, LUMI)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NS = [1, 1024, 65536, 1048576, 16777216]
MS = [1, 2]
STG = "CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_CHUNK_BYTES=1048576"
HK = "COPYLIB_HOST_KERNEL=1 CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_CHUNK_BYTES=1048576 COPYLIB_MAX_ELEM_SIZE=4 COPYLIB_ELEMS_PER_ITEM=4 COPYLIB_WG_SIZE=256"
ENVS = [f"{b} COPYLIB_PRELOAD_KERNELS={p}" for b in (STG, HK) for p in (1, 0)]
METRICS = {"machine": r"^(\\S+)", "buffer_creation_gbps": r"buffer creation:.*?([0-9]+\\.[0-9]+)GB/s", "copy_bandwidth": r"first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
           "d2h_gbps": r"device to host:.*?([0-9]+\\.[0-9]+)GB/s", "check": r"Check: (\\w+)", "data_size_gib": r"Worked on Data Size:\\s*([0-9.]+)\\s*GiB"}
APPS = [("Celerity-acpp", "~/finalizing-work/build/bench-transfer-acpp-bench/strided_transfer"),
        ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && {env} ~/finalizing-work/build/bench-transfer-dpcpp0326-bench/strided_transfer")]


def yaml(system, name, envs):
    prefix = "ROCR_VISIBLE_DEVICES=4 " if system == "lumi" else ""
    out = ["# generated by make_preload_yamls.py", "iterations: 8", "warmup_iterations: 1", f"output_csv: 17_preload/{system}/results/{name}.csv", "", "applications:"]
    for app, exe in APPS:
        cmd = f"hostname; {prefix}{{env}} {exe} {{N}} {{M}}" if app.endswith("acpp") else f"hostname; {exe.replace('{env} ', '{env} ' + prefix)} {{N}} {{M}}"
        out += [f"  - name: {app}", f'    command: "{cmd}"', "    parameters:", f"      N: {NS}", f"      M: {MS}", "      env: [" + ", ".join(f'"{e}"' for e in envs) + "]",
                "    metrics:"] + [f'      {k}: "{v}"' for k, v in METRICS.items()]
        out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "strided_transfer", config: "{name}"}}', ""]
    return "\n".join(out)


def main():
    plan = {"gpuc4": ["preload"], "ifi": ["preload_gc20", "preload_gc22"], "lumi": ["preload"]}
    for system, names in plan.items():
        os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
        for i, name in enumerate(names):
            with open(os.path.join(HERE, system, name + ".yaml"), "w") as f:
                f.write(yaml(system, name, ENVS if i == 0 else ENVS[::-1]) + "\n")
    with open(os.path.join(HERE, "gpuc4", "chain.sh"), "w") as f:
        f.write("#!/bin/sh\n# runs the preload study on gpuc4\ncd ~/finalizing-work/benchmarks\nmd5sum benchmark_wrapper.py\n"
                "for f in 17_preload/gpuc4/preload.yaml; do\n\techo \"=== $f $(date +%H:%M)\"\n\ttimeout 3h python3 -u benchmark_wrapper.py $f | grep -E \"phase|Done|Error|Traceback\"\ndone\n"
                "echo PRELOAD-DONE $(date +%H:%M)\n")
    with open(os.path.join(HERE, "ifi", "jobs.txt"), "w") as f:
        f.write("gc20 17_preload/ifi/preload_gc20.yaml\ngc22 17_preload/ifi/preload_gc22.yaml\n")
    with open(os.path.join(HERE, "lumi", "jobs.txt"), "w") as f:
        f.write("- 17_preload/lumi/preload.yaml\n")


if __name__ == "__main__":
    main()
