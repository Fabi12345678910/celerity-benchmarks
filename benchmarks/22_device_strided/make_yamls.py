#!/usr/bin/env python3
"""Generates the YAMLs of the device-strided study: device_strided_transfer (contiguous on the host, strided on the device, both directions) with the
sweep 4 base configs, both SYCL implementations, M 1, 2, 4 and N 1..2^28 on gpuc4, ifi and LUMI:
  device_stg_base     staging, 4 queues, 1 MiB chunks, SDMA off
  device_hk_base      host kernel, 4 queues, 1 MiB chunks, MAX_ELEM_SIZE 4, 4 elements per item, work-group 256, SDMA off
  device_native_1/_2  Celerity without copylib (CELERITY_COPYLIB=off, SDMA off), N up to 2^23 like the earlier native configs (M 1, 2 / M 4)
Writes <system>/<name>.yaml, gpuc4/chain.sh and <system>/jobs.txt (one job per line). Usage: python3 make_yamls.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FULL = ", ".join(str(2 ** i) for i in range(29))
SMALL = ", ".join(str(2 ** i) for i in range(24))
STG = "HSA_ENABLE_SDMA=0 CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_CHUNK_BYTES=1048576"
HK = "HSA_ENABLE_SDMA=0 COPYLIB_HOST_KERNEL=1 CELERITY_COPYLIB_QUEUES=4 CELERITY_COPYLIB_CHUNK_BYTES=1048576 COPYLIB_MAX_ELEM_SIZE=4 COPYLIB_ELEMS_PER_ITEM=4 COPYLIB_WG_SIZE=256"
CONFIGS = [("device_stg_base", "staging", STG, FULL, "1, 2, 4"), ("device_hk_base", "host kernel", HK, FULL, "1, 2, 4"),
           ("device_native_1", "native", "HSA_ENABLE_SDMA=0 CELERITY_COPYLIB=off", SMALL, "1, 2"), ("device_native_2", "native", "HSA_ENABLE_SDMA=0 CELERITY_COPYLIB=off", SMALL, "4")]
METRICS = {"machine": r"^(\\S+)", "buffer_creation_gbps": r"buffer creation:.*?([0-9]+\\.[0-9]+)GB/s", "copy_bandwidth": r"first access.*?:.*?([0-9]+\\.[0-9]+)GB/s",
           "read_only_gbps": r"read only:.*?([0-9]+\\.[0-9]+)GB/s", "read_write_gbps": r"read write:.*?([0-9]+\\.[0-9]+)GB/s",
           "d2h_gbps": r"device to host:.*?([0-9]+\\.[0-9]+)GB/s", "check": r"Check: (\\w+)", "full_data_size_gib": r"Data Size:\\s*([0-9.]+)\\s*GiB",
           "data_size_gib": r"Worked on Data Size:\\s*([0-9.]+)\\s*GiB"}
IMPLS = [("Celerity-acpp", "", "bench-device_strided-acpp-bench"),
         ("Celerity-dpcpp", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ", "bench-device_strided-dpcpp0326-bench")]


def main():
    for system in ("gpuc4", "ifi", "lumi"):
        os.makedirs(os.path.join(HERE, system, "results"), exist_ok=True)
        prefix = "ROCR_VISIBLE_DEVICES=4 " if system == "lumi" else ""
        names = []
        for name, variant, env, ns, ms in CONFIGS:
            out = ["# generated by make_yamls.py", "iterations: 3", "warmup_iterations: 1", f"output_csv: 22_device_strided/{system}/results/{name}.csv", "", "applications:"]
            for app, source, build in IMPLS:
                out += [f"  - name: {app}", f'    command: "hostname; {source}{prefix}{{env}} ~/finalizing-work/build/{build}/device_strided_transfer {{N}} {{M}}"',
                        "    parameters:", f'      env: ["{env}"]', f"      N: [{ns}]", f"      M: [{ms}]", "    metrics:"]
                out += [f'      {k}: "{x}"' for k, x in METRICS.items()]
                out += [f'    static: {{celerity: "3dcopylib-bench 2dda28f", program: "device_strided_transfer", variant: "{variant}", config: "{name}"}}', ""]
            open(os.path.join(HERE, system, name + ".yaml"), "w").write("\n".join(out).rstrip() + "\n")
            names.append(f"22_device_strided/{system}/{name}.yaml")
        jobs = [names[:2], names[2:]]  # the staged and host-kernel runs, then the native ones
        open(os.path.join(HERE, system, "jobs.txt"), "w").write("".join(" ".join(j) + "\n" for j in jobs))
        if system == "gpuc4":
            open(os.path.join(HERE, system, "chain.sh"), "w").write(
                "#!/bin/sh\n# runs the device-strided study on gpuc4\ncd ~/finalizing-work/benchmarks\nmd5sum benchmark_wrapper.py\nfor f in " + " ".join(names) +
                "; do\n\tcsv=$(sed -n 's/^output_csv: //p' $f)\n\t[ -s \"$csv\" ] && continue\n\techo \"=== $f $(date +%H:%M)\"\n\ttimeout 3h python3 -u benchmark_wrapper.py $f | grep -E \"phase|Done|Error|Traceback\"\ndone\necho DEVICE-DONE $(date +%H:%M)\n")


if __name__ == "__main__":
    main()
