#!/usr/bin/env python3
"""A/B test of the clean library's copy kernel on LUMI (2026-10-08): final2 (81b2cb2, clean kernel), final3 (4dc8061, clean
kernel with the bench index form) and final-bench (f24e5f0, bench kernel) on the discriminating cases: device_strided_transfer and
strided_both_transfer, host to device, staging and host kernel, AdaptiveCpp and DPC++. One YAML per program; the three builds are applications of the
same YAML, so every iteration runs them one after another on the same node (drift cancels). 5 iterations + 1 warm-up, N = 2^20..2^28 (both: 2^24).
Writes ab/lumi/ab_<program>.yaml (results ab/lumi/results/). Usage: python3 make_ab_yamls.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BUILDS = [("final2", "3dcopylib-final 81b2cb2"), ("final3", "exp-final3 4dc8061"), ("final-bench", "3dcopylib-final-bench f24e5f0")]
IMPLS = [("acpp", ""), ("dpcpp0326", ". ~/finalizing-work/install/dpcpp-nightly-2026-03-26/env.sh && ")]
PROGS = {"device": ("device_strided_transfer", "bench-device_strided-{impl}-{b}", [2 ** i for i in range(20, 29, 2)], [2, 4]),
         "both": ("strided_both_transfer", "bench-both_strided-{impl}-{b}", [2 ** i for i in range(20, 25, 2)], [2, 64])}
ENVS = ["HSA_ENABLE_SDMA=0", "HSA_ENABLE_SDMA=0 COPYLIB_HOST_KERNEL=1"]
METRICS = {"machine": "^(\\\\S+)", "copy_bandwidth": "first access.*?:.*?([0-9]+\\\\.[0-9]+)GB/s", "d2h_gbps": "device to host:.*?([0-9]+\\\\.[0-9]+)GB/s",
           "check": "Check: (\\\\w+)"}


def q(s):
    return '"' + s + '"'


for key, (prog, build, ns, ms) in PROGS.items():
    lines = ["# generated by make_ab_yamls.py", "iterations: 5", "warmup_iterations: 1", f"output_csv: 25_final/ab/lumi/results/ab_{key}.csv", "", "applications:"]
    for b, cel in BUILDS:
        for impl, src in IMPLS:
            path = "~/finalizing-work/build/" + build.format(impl=impl, b=b) + "/" + prog
            lines += [f"  - name: {b}-{impl}", f"    command: {q(f'hostname; {src}ROCR_VISIBLE_DEVICES=4 {{env}} {path} {{N}} {{M}}')}", "    parameters:",
                      f"      N: [{', '.join(map(str, ns))}]", f"      M: [{', '.join(map(str, ms))}]", f"      env: [{', '.join(q(e) for e in ENVS)}]", "    metrics:"]
            lines += [f"      {k}: {q(v)}" for k, v in METRICS.items()]
            lines += ["    static: {" + f'build: "{b}", impl: "{impl}", celerity: "{cel}", program: "{prog}"' + "}", ""]
    os.makedirs(os.path.join(HERE, "lumi", "results"), exist_ok=True)
    open(os.path.join(HERE, "lumi", f"ab_{key}.yaml"), "w").write("\n".join(lines).rstrip() + "\n")
print("written")
